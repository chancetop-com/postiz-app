#!/usr/bin/env node
// Ticket 18 — map every net path of the two customization commits onto its
// final representation.
//
// Input : .scratch/postiz-stable-merge/assets/customization-path-tracking.tsv
//         (863 paths = git diff --name-only 0b554e68 6fdf7cb5)
// Output: .scratch/postiz-stable-merge/assets/final-customization-appendix.tsv
//
// Usage: node .scratch/postiz-stable-merge-implementation/rehearsals/18/generate-customization-appendix.mjs

import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const UPSTREAM = 'a5affe62c74e39c1e7ac960d50d8418b807d532c';
const CUSTOMIZATION = '6fdf7cb53543fa28a470ad63e7619e8b98bcee43';
const TRACKER = '.scratch/postiz-stable-merge/assets/customization-path-tracking.tsv';
const OUT = '.scratch/postiz-stable-merge/assets/final-customization-appendix.tsv';

const git = (args) => spawnSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 28 });
const inCommit = (commit, path) => git(['cat-file', '-e', `${commit}:${path}`]).status === 0;

const VERIFIED_BY = {
  'image-runtime': '13 + 18 (image rehearsal, build-context/runtime contract tests)',
  'merge-stable-release': '02 + 18 (merge, final gates, this appendix)',
  'merchant-sso': '04 (merchant-sso-entry/routes/account-org/session, standard routes, cookie gate)',
  'session-organization-login': '05 (session-org-flow, tab, popup, lifecycle, 401, upload, copilot, oauth state)',
  'brand-theme-navigation': '06 (seven render suites) + 10 (media toolbar)',
  'channel-oauth-direct': '07 (eight suites: entries, popup contract, callback, relay)',
  'optional-services': '12 (copilot, mcp, core flows)',
  'media-editing': '10 (library, editor, upload route/server, processing, api)',
  'public-preview': '11 (loader, route, preview auth)',
  'startup-sync-data-retention': '03 (49 assertions) + 18 (re-run on the final image)',
};

const rows = readFileSync(TRACKER, 'utf8').trim().split('\n');
const header = rows.shift().split('\t');
const idx = Object.fromEntries(header.map((h, i) => [h, i]));

const out = [
  [
    'path',
    'area',
    'owning_ticket',
    'tracker_disposition',
    'present_in_final',
    'present_in_customization_C',
    'identical_to_C',
    'final_status_vs_upstream',
    'preserved_as',
    'final_implementation',
    'verified_by',
  ],
];

const summary = {};
for (const line of rows) {
  const cols = line.split('\t');
  const path = cols[idx.path];
  const disposition = cols[idx.disposition];
  const area = cols[idx.area];
  const ticket = cols[idx.owning_ticket];
  const notes = cols[idx.notes] || '';

  const inFinal = inCommit('HEAD', path);
  const inC = inCommit(CUSTOMIZATION, path);
  const identical = inC && git(['diff', '--quiet', CUSTOMIZATION, 'HEAD', '--', path]).status === 0;
  const inUpstream = inCommit(UPSTREAM, path);

  let status = 'absent-in-both';
  if (inFinal && inUpstream) {
    status = git(['diff', '--quiet', UPSTREAM, 'HEAD', '--', path]).status === 0 ? 'identical-to-upstream' : 'differs-from-upstream';
  } else if (inFinal) status = 'not-in-upstream';
  else if (inUpstream) status = 'removed';

  let preservedAs;
  let implementation;
  if (disposition === 'generated-copy') {
    preservedAs = inFinal ? 'regenerated mirror' : 'mirror path gone';
    implementation = inFinal
      ? 'k8s/apps|k8s/libraries mirror regenerated by k8s/prepare-build-context.sh from the merged root source'
      : 'the merged root source no longer produces this mirror path (upstream removed or renamed it)';
  } else if (disposition === 'retained') {
    preservedAs = inFinal ? (identical ? 'kept verbatim' : 'kept, re-adapted') : 'missing';
    implementation = inFinal ? 'present at the same path in the merged tree' : 'NOT PRESENT — investigated';
  } else if (disposition === 'adapted') {
    preservedAs = inFinal ? 'merged and re-adapted' : 'missing';
    implementation = inFinal ? 'present at the same path; content combines the fork change with the upstream change' : 'NOT PRESENT — investigated';
  } else if (disposition === 'upstream-replaced') {
    preservedAs = 'upstream version kept';
    implementation = 'merged content equals the upstream stable version; the fork edit was a typing workaround with no behavioural effect';
  } else {
    preservedAs = 'mirror path gone';
    implementation = 'the upstream history removed the corresponding root source (farcaster/Neynar migration, PostHog removal, nowpayments and veo3 removal, bounded media reads), so the regenerated mirror no longer contains this path; nothing was hand-deleted';
  }

  summary[preservedAs] = (summary[preservedAs] || 0) + 1;
  out.push([
    path,
    area,
    ticket,
    disposition,
    inFinal ? 'yes' : 'no',
    inC ? 'yes' : 'no',
    identical ? 'yes' : 'no',
    status,
    preservedAs,
    implementation,
    VERIFIED_BY[area] || 'ticket 18',
  ]);
}

writeFileSync(OUT, out.map((r) => r.join('\t')).join('\n') + '\n');
console.log(`wrote ${OUT}: ${out.length - 1} customization paths`);
console.log(summary);
